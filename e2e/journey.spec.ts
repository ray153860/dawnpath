import {expect,test} from '@playwright/test'

test('topic reflection, separate activity result, restart and history',async({page})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{name:/兴趣不是一次选择/})).toBeVisible()
 await page.getByRole('button',{name:/开始我的探索/}).click()
 await expect(page.getByRole('heading',{name:/哪些主题/})).toBeVisible()
 await page.getByRole('button',{name:'哲学兴趣 4 分'}).click()
 await page.getByRole('button',{name:/继续活动方式/}).click()
 await page.getByRole('button',{name:'分析推理第 1 题 4 分'}).click()
 await page.getByRole('button',{name:/保存并查看探索报告/}).click()
 await expect(page.getByText('主题兴趣 4/4 · 有兴趣线索')).toBeVisible()
 await expect(page.getByText(/分析推理：4.0\/4/)).toBeVisible()
 await expect(page.getByText(/已评价 1 个、信息不足 0 个、未回答 11 个/)).toBeVisible()
 await page.getByRole('button',{name:'重新测评'}).click()
 await expect(page.getByRole('heading',{name:/哪些主题/})).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'我的足迹'}).click()
 await expect(page.getByText(/1 个学科主题回答/)).toBeVisible()
})

