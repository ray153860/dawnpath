test('mobile export, clear and restore',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await page.getByRole('button',{name:/开始我的探索/}).click()
 await page.getByRole('button',{name:'哲学兴趣 0 分'}).click()
 await page.getByRole('button',{name:/继续活动方式/}).click()
 await page.getByRole('button',{name:/保存并查看探索报告/}).click()
 await expect(page.getByText('主题兴趣 0/4 · 不感兴趣')).toBeVisible()
 await page.getByRole('button',{name:'我的足迹'}).click()
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'导出 JSON'}).click()
 const download=await downloadPromise
 expect(download.suggestedFilename()).toBe('dawnpath-data.json')
 const exported=await page.evaluate(()=>localStorage.getItem('dp-records'))
 expect(JSON.parse(exported??'[]')).toHaveLength(1)
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'清除全部数据'}).click()
 await expect(page.getByText(/还没有记录/)).toBeVisible()
 const chooser=page.waitForEvent('filechooser')
 await page.getByRole('button',{name:'恢复 JSON'}).click()
 page.once('dialog',dialog=>dialog.accept())
 await (await chooser).setFiles(await download.path()??'')
 await expect(page.getByText(/1 个学科主题回答/)).toBeVisible()
})
